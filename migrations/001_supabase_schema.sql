create or replace function public.create_match_on_like()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.kind <> 'like' then
    return new;
  end if;

  if exists (
    select 1
    from public.likes l
    where l.from_id = new.to_id
      and l.to_id = new.from_id
      and l.kind = 'like'
  ) then
    insert into public.matches(a, b)
    values (least(new.from_id, new.to_id), greatest(new.from_id, new.to_id))
    on conflict (a, b) do nothing;
  end if;

  return new;
end;
$$;

