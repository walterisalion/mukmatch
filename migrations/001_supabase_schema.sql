    create policy photos_insert_own_folder
    on storage.objects
    for insert
    to authenticated
    with check (
      bucket_id = 'photos'
      and (storage.foldername(name))[1] = auth.uid()::text
    );
  end if;

  if not exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='photos_update_own_folder') then
    create policy photos_update_own_folder
    on storage.objects
    for update
    to authenticated
    using (
      bucket_id = 'photos'
      and (storage.foldername(name))[1] = auth.uid()::text
    )
    with check (
      bucket_id = 'photos'
      and (storage.foldername(name))[1] = auth.uid()::text
    );
  end if;

  if not exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='photos_delete_owner_or_admin') then
    create policy photos_delete_owner_or_admin
    on storage.objects
    for delete
    to authenticated
    using (
      bucket_id = 'photos'
      and (
        (storage.foldername(name))[1] = auth.uid()::text
        or public.is_admin(auth.uid())
      )
    );
  end if;
end $$;

