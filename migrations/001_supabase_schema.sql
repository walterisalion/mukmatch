create or replace function public.admin_remove_profile(target uuid, note text default null)
returns text[]
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_paths text[] := '{}'::text[];
  v_profile_name text := 'Unknown';
  v_reasons text[] := '{}'::text[];
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if not exists (select 1 from public.admins a where a.user_id = auth.uid()) then
    raise exception 'Not authorised';
  end if;

  if target is null then
    raise exception 'Target is required';
  end if;

  if target = auth.uid() then
    raise exception 'Organisers cannot remove their own account with this action';
  end if;

  select coalesce(p.photos, '{}'::text[]), coalesce(p.name, 'Unknown')
  into v_paths, v_profile_name
  from public.profiles p
  where p.id = target;

  select coalesce(array_agg(r.reason order by r.created_at desc), '{}'::text[])
  into v_reasons
  from public.reports r
  where r.reported = target and r.resolved = false;

  insert into public.mod_log(target_user, target_name, note, report_reasons)
  values (target, v_profile_name, nullif(trim(note), ''), v_reasons);

  update public.reports
  set resolved = true
  where reported = target and resolved = false;

  delete from auth.users where id = target;

  return v_paths;
end;
$$;

