create or replace function public.unread_summary()
returns table(match_id bigint, unread integer)
language sql
stable
security invoker
set search_path = public
as $$
  select
    m.id as match_id,
    coalesce(count(msg.id), 0)::integer as unread
  from public.matches m
  left join public.reads r
    on r.match_id = m.id
   and r.user_id = auth.uid()
  left join public.messages msg
    on msg.match_id = m.id
   and msg.sender <> auth.uid()
   and (r.last_read is null or msg.created_at > r.last_read)
  where m.a = auth.uid() or m.b = auth.uid()
  group by m.id;
$$;

